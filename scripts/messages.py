def pick(node, i):
    return {k: (pick(v, i) if isinstance(v, dict) else v[i]) for k, v in node.items()}

root = os.path.join(os.path.dirname(__file__), '..', 'messages')
for i, loc in enumerate(['fa', 'en']):
    with open(os.path.join(root, f'{loc}.json'), 'w', encoding='utf-8') as f:
        json.dump(pick(M, i), f, ensure_ascii=False, indent=2)
        f.write('\n')
